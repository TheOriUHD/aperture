import type { ArchId } from "./arch";

// The CPU catalogue for the hardware profile. Each entry is described by its core
// clusters (count, microarchitecture, top clock, SMT), and its capacity comes from
// those through one rule (capacity.ts) — no per-model magic numbers. Clocks are the
// maximum turbo/boost of each cluster; the model derates them to sustained
// all-core speed.

export type Vendor = "Intel" | "AMD" | "Apple" | "Raspberry Pi" | "Rockchip" | "Amlogic" | "NVIDIA" | "Qualcomm" | "Ampere" | "AWS" | "Realtek" | "Annapurna Labs" | "Marvell" | "Broadcom";
export type Segment = "Desktop" | "Laptop & mini PC" | "Low power & NAS" | "Server & workstation" | "Single-board & embedded" | "Apple";

export interface Cluster {
  n: number;
  arch: ArchId;
  ghz: number;
  smt?: boolean;
}

export interface CpuSpec {
  id: string;
  name: string;
  vendor: Vendor;
  segment: Segment;
  year: number;
  clusters: Cluster[];
  threads: number;
  igpu?: string;
  aliases?: string[];
}

const slug = (s: string) =>
  s
    .toLowerCase()
    .replace(/\+/g, "plus")
    .replace(/[^a-z0-9]+/g, "-")
    .replace(/^-|-$/g, "");

// x86 with one kind of core; threads > cores means SMT/Hyper-Threading.
function x(vendor: Vendor, segment: Segment, name: string, year: number, cores: number, threads: number, boost: number, arch: ArchId, igpu?: string, aliases?: string[]): CpuSpec {
  return { id: slug(`${vendor} ${name}`), name: `${vendor} ${name}`, vendor, segment, year, threads, igpu, aliases, clusters: [{ n: cores, arch, ghz: boost, smt: threads > cores }] };
}
// Hybrid x86: performance cores (with Hyper-Threading when threads say so) plus
// efficient cores, and optionally low-power island cores.
function h(segment: Segment, name: string, year: number, p: number, e: number, threads: number, pGhz: number, eGhz: number, pArch: ArchId, eArch: ArchId, igpu?: string, lpe = 0, aliases?: string[]): CpuSpec {
  const clusters: Cluster[] = [{ n: p, arch: pArch, ghz: pGhz, smt: threads > p + e + lpe }];
  if (e) clusters.push({ n: e, arch: eArch, ghz: eGhz });
  if (lpe) clusters.push({ n: lpe, arch: "crestmont", ghz: 2.5 });
  return { id: slug(`Intel ${name}`), name: `Intel ${name}`, vendor: "Intel", segment, year, threads, igpu, aliases, clusters };
}
// Arm and other SoCs: explicit clusters [count, arch, GHz].
function soc(vendor: Vendor, segment: Segment, name: string, year: number, clusters: [number, ArchId, number][], aliases?: string[], igpu?: string): CpuSpec {
  const cl = clusters.map(([n, arch, ghz]) => ({ n, arch, ghz }));
  const full = name.startsWith(vendor) ? name : `${vendor} ${name}`;
  return { id: slug(full), name: full, vendor, segment, year, threads: cl.reduce((a, c) => a + c.n, 0), igpu, aliases, clusters: cl };
}

