import { useState, type InputHTMLAttributes, type ReactNode } from "react";
import { useTranslation } from "react-i18next";
import { AlertCircle, Eye, EyeOff, Info } from "lucide-react";
import clsx from "clsx";
import sceneSvg from "../assets/scene.svg?raw";

// AuthLayout frames every signed-out screen (sign-in, first-run setup, the
// forced password change and 2FA enrollment) the way a Protect console's
// sign-in does: a narrow form panel with the product mark on the left, the
// device on the right. Below lg the device goes and the form panel fills the
// screen. The panel scrolls on its own when a step is taller than the screen
// (the 2FA QR step on a phone with the keyboard up).
export function AuthLayout({ title, subtitle, children }: { title?: string; subtitle?: string; children: ReactNode }) {
  return (
    <div className="flex h-full bg-ink-900">
      <main className="h-full w-full overflow-y-auto lg:w-[440px] lg:shrink-0">
        <div
          className="mx-auto flex min-h-full w-full max-w-[400px] flex-col px-6 sm:px-10 lg:max-w-none lg:px-[68px]"
          style={{
            paddingTop: "max(4.5rem, calc(env(safe-area-inset-top) + 2.5rem))",
            paddingBottom: "max(2.5rem, env(safe-area-inset-bottom))",
          }}
        >
          <Wordmark className="mb-14 self-center" />
          <div className="animate-fade-in">
            {title && (
              <div className="mb-7">
                <h1 className="text-lg font-semibold text-fg">{title}</h1>
                {subtitle && <p className="mt-1 text-pretty text-sm leading-relaxed text-fg-muted">{subtitle}</p>}
              </div>
            )}
            {children}
          </div>
        </div>
      </main>

      <section aria-hidden className="relative hidden min-w-0 flex-1 overflow-hidden bg-ink-850 lg:block">
        <div
          className="absolute inset-0"
          style={{ background: "radial-gradient(58% 52% at 50% 44%, rgba(255,255,255,0.06), rgba(255,255,255,0) 72%)" }}
        />
        <div className="relative flex h-full flex-col items-center justify-center px-12 pb-[4vh]">
          <SceneArt />
          <p className="mt-[4vh] text-[34px] font-light tracking-[-0.01em] text-fg/90">Aperture NVR</p>
        </div>
      </section>
    </div>
  );
}

// SceneArt is the isometric picture of the system (cameras, network, the NVR,
// storage, a phone and the cloud), generated by web/scripts/render-scene.mjs.
// It is inlined so its animations run. (The earlier single-device render is kept
// in assets/saved/, made by web/scripts/render-nvr.mjs.)
function SceneArt() {
  return (
    <div
      className="w-[min(860px,88%)] select-none animate-fade-in [&>svg]:mx-auto [&>svg]:block [&>svg]:h-auto [&>svg]:max-h-[62vh] [&>svg]:w-full"
      // A build-time asset of our own, not user content.
      dangerouslySetInnerHTML={{ __html: sceneSvg }}
    />
  );
}

// The product mark (the app icon's lens) and name.
function Wordmark({ className }: { className?: string }) {
  return (
    <div className={clsx("flex items-center gap-3", className)}>
      <svg viewBox="0 0 32 32" className="h-[30px] w-[30px] text-brand" aria-hidden>
        <circle cx="16" cy="16" r="13.8" fill="none" stroke="currentColor" strokeWidth="4.4" />
        <circle cx="16" cy="16" r="6.9" fill="currentColor" />
      </svg>
      <span className="text-[30px] font-semibold leading-none tracking-[-0.015em] text-fg">Aperture</span>
    </div>
  );
}

type FieldProps = { label: string; trailing?: ReactNode; inputClassName?: string } & InputHTMLAttributes<HTMLInputElement>;

// AuthField is a sign-in field: a small label above and a single underline that
// turns blue while you type in it.
export function AuthField({ label, trailing, className, inputClassName, ...input }: FieldProps) {
  return (
    <div className={clsx("group", className)}>
      <label htmlFor={input.id} className="block text-[13px] leading-5 text-fg-muted transition-colors group-focus-within:text-brand">
        {label}
      </label>
      <div className="flex items-center gap-1 border-b border-white/[0.14] transition-colors hover:border-white/25 group-focus-within:!border-brand">
        <input {...input} className={clsx("auth-input", inputClassName)} />
        {trailing}
      </div>
    </div>
  );
}

// PasswordField is an AuthField with the show/hide toggle.
export function PasswordField(props: Omit<FieldProps, "type" | "trailing">) {
  const { t } = useTranslation();
  const [show, setShow] = useState(false);
  return (
    <AuthField
      {...props}
      type={show ? "text" : "password"}
      trailing={
        <button
          type="button"
          onClick={() => setShow((s) => !s)}
          aria-label={show ? t("auth.hidePassword", "Hide password") : t("auth.showPassword", "Show password")}
          aria-pressed={show}
          className="-mr-1.5 grid h-8 w-8 shrink-0 place-items-center rounded-md text-fg-faint transition-colors hover:text-fg focus-visible:outline-none focus-visible:ring-2 focus-visible:ring-brand/60"
        >
          {show ? <Eye className="h-[18px] w-[18px]" /> : <EyeOff className="h-[18px] w-[18px]" />}
        </button>
      }
    />
  );
}

// AuthCheck is a checkbox with a label and an optional quieter line under it.
export function AuthCheck({
  checked,
  onChange,
  label,
  hint,
}: {
  checked: boolean;
  onChange: (v: boolean) => void;
  label: ReactNode;
  hint?: ReactNode;
}) {
  return (
    <label className="flex cursor-pointer select-none items-start gap-2.5">
      <input type="checkbox" className="mt-0.5 h-4 w-4 shrink-0" checked={checked} onChange={(e) => onChange(e.target.checked)} />
      <span>
        <span className="block text-sm text-fg">{label}</span>
        {hint && <span className="mt-0.5 block text-xs leading-relaxed text-fg-faint">{hint}</span>}
      </span>
    </label>
  );
}

// AuthNote is the quiet info box under a sign-in form.
export function AuthNote({ children, className }: { children: ReactNode; className?: string }) {
  return (
    <div className={clsx("flex gap-2.5 rounded-md bg-ink-800 px-3.5 py-3 text-[13px] leading-relaxed text-fg-muted", className)}>
      <Info className="mt-[3px] h-4 w-4 shrink-0 text-brand" />
      <div className="min-w-0">{children}</div>
    </div>
  );
}

// AuthError is the inline error line under a sign-in form.
export function AuthError({ children }: { children: ReactNode }) {
  return (
    <p role="alert" className="flex items-start gap-2 rounded-md bg-danger/10 px-3 py-2 text-sm text-danger">
      <AlertCircle className="mt-0.5 h-4 w-4 shrink-0" />
      <span className="min-w-0">{children}</span>
    </p>
  );
}

// AuthDivider is the "or" rule between password and alternative sign-ins.
export function AuthDivider({ children }: { children: ReactNode }) {
  return (
    <div className="my-6 flex items-center gap-3 text-fg-faint">
      <span className="h-px flex-1 bg-line-strong" />
      <span className="text-xs">{children}</span>
      <span className="h-px flex-1 bg-line-strong" />
    </div>
  );
}
